-- ===================================================
-- VIEWS FOR EASY REPORTING
-- ===================================================

-- Drop view if exists to avoid conflicts
DROP VIEW IF EXISTS project_assessments_latest;

-- Create view for latest assessments
CREATE VIEW project_assessments_latest AS
SELECT 
    p.project_id,
    p.project_name,
    p.industry,
    p.budget,
    p.created_at,
    sp.success_probability,
    sp.overall_risk_score,
    sp.confidence_score,
    sp.prediction_date,
    swot.strengths,
    swot.weaknesses,
    swot.opportunities,
    swot.threats,
    swot.summary as swot_summary,
    (SELECT json_agg(rec.*) FROM recommendations rec WHERE rec.project_id = p.project_id AND rec.is_latest = true) as recommendations
FROM projects p
LEFT JOIN success_predictions sp ON p.project_id = sp.project_id AND sp.is_latest = true
LEFT JOIN swot_analysis swot ON p.project_id = swot.project_id AND swot.is_latest = true;

COMMENT ON VIEW project_assessments_latest IS 'Latest assessment data for all projects';

