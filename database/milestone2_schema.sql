-- ===================================================
-- MILESTONE 2 - COMPLETE DATABASE SCHEMA
-- AI-Powered Product Intelligence System
-- ===================================================

-- Enable UUID extension for better security
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ===================================================
-- 1. USERS TABLE
-- ===================================================
CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    role VARCHAR(50) DEFAULT 'user' NOT NULL,
    is_active BOOLEAN DEFAULT true,
    last_login TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE users IS 'Stores registered users of the system';
COMMENT ON COLUMN users.password_hash IS 'Bcrypt or Argon2 hashed password';
COMMENT ON COLUMN users.role IS 'User role: admin, analyst, user';

-- ===================================================
-- 2. PROJECTS TABLE
-- ===================================================
CREATE TABLE IF NOT EXISTS projects (
    project_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    project_name VARCHAR(255) NOT NULL,
    project_type VARCHAR(100),
    industry VARCHAR(100),
    business_model VARCHAR(100),
    target_market TEXT,
    budget NUMERIC(15, 2),
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_projects_users FOREIGN KEY (user_id) 
        REFERENCES users(user_id) ON DELETE CASCADE ON UPDATE CASCADE
);

COMMENT ON TABLE projects IS 'Stores core project information submitted by users';
COMMENT ON COLUMN projects.budget IS 'Project budget in USD';

-- ===================================================
-- 3. ANALYTICS_LOGS TABLE
-- ===================================================
CREATE TABLE IF NOT EXISTS analytics_logs (
    log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    activity_type VARCHAR(100) NOT NULL,
    activity_details JSONB,
    ip_address INET,
    user_agent TEXT,
    timestamp TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_analytics_logs_users FOREIGN KEY (user_id) 
        REFERENCES users(user_id) ON DELETE SET NULL ON UPDATE CASCADE
);

COMMENT ON TABLE analytics_logs IS 'Stores user/system activity logs for analytics and auditing';
COMMENT ON COLUMN analytics_logs.activity_details IS 'JSONB field for additional activity context';

-- ===================================================
-- 4. ANALYTICS TABLE
-- ===================================================
CREATE TABLE IF NOT EXISTS analytics (
    usg_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    project_type VARCHAR(100),
    project_budget NUMERIC(15, 2),
    markets JSONB,
    industry VARCHAR(100),
    analysis_data JSONB,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    generated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_analytics_projects FOREIGN KEY (project_id) 
        REFERENCES projects(project_id) ON DELETE CASCADE ON UPDATE CASCADE
);

COMMENT ON TABLE analytics IS 'Stores analytical information generated from project data';
COMMENT ON COLUMN analytics.markets IS 'JSONB array of target markets';
COMMENT ON COLUMN analytics.analysis_data IS 'JSONB field for flexible analysis data storage';

-- ===================================================
-- 5. COMPETITOR_ANALYSIS TABLE
-- ===================================================
CREATE TABLE IF NOT EXISTS competitor_analysis (
    analysis_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    competitor_name VARCHAR(255) NOT NULL,
    market_position VARCHAR(50),
    competitive_risk VARCHAR(20) CHECK (competitive_risk IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    analysis_details JSONB,
    analysis_date TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_competitor_analysis_projects FOREIGN KEY (project_id) 
        REFERENCES projects(project_id) ON DELETE CASCADE ON UPDATE CASCADE
);

COMMENT ON TABLE competitor_analysis IS 'Stores competitor and market analysis for projects';
COMMENT ON COLUMN competitor_analysis.competitive_risk IS 'Risk level: LOW, MEDIUM, HIGH, CRITICAL';

-- ===================================================
-- 6. RISK_ASSESSMENTS TABLE (CORE MILESTONE 2)
-- ===================================================
CREATE TABLE IF NOT EXISTS risk_assessments (
    risk_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    risk_category VARCHAR(50) NOT NULL CHECK (risk_category IN (
        'Financial', 'Market', 'Technical', 'Business', 'Execution', 
        'Operational', 'Regulatory', 'Strategic', 'Competitive'
    )),
    risk_score INTEGER CHECK (risk_score >= 0 AND risk_score <= 100),
    risk_description TEXT,
    impact_assessment TEXT,
    priority_level VARCHAR(20) CHECK (priority_level IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    mitigation_strategy TEXT,
    assessment_date TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_risk_assessments_projects FOREIGN KEY (project_id) 
        REFERENCES projects(project_id) ON DELETE CASCADE ON UPDATE CASCADE
);

COMMENT ON TABLE risk_assessments IS 'Stores risk analysis generated for each project (Milestone 2 Core)';
COMMENT ON COLUMN risk_assessments.risk_score IS 'Risk score from 0-100';
COMMENT ON COLUMN risk_assessments.priority_level IS 'Priority: LOW, MEDIUM, HIGH, CRITICAL';

-- ===================================================
-- 7. SWOT_ANALYSIS TABLE (CORE MILESTONE 2)
-- ===================================================
CREATE TABLE IF NOT EXISTS swot_analysis (
    swot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    strengths JSONB NOT NULL,
    weaknesses JSONB NOT NULL,
    opportunities JSONB NOT NULL,
    threats JSONB NOT NULL,
    summary TEXT,
    generated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    is_latest BOOLEAN DEFAULT true,
    CONSTRAINT fk_swot_analysis_projects FOREIGN KEY (project_id) 
        REFERENCES projects(project_id) ON DELETE CASCADE ON UPDATE CASCADE
);

COMMENT ON TABLE swot_analysis IS 'Stores automatically generated SWOT analysis (Milestone 2 Core)';
COMMENT ON COLUMN swot_analysis.strengths IS 'JSONB array of strengths';
COMMENT ON COLUMN swot_analysis.weaknesses IS 'JSONB array of weaknesses';
COMMENT ON COLUMN swot_analysis.opportunities IS 'JSONB array of opportunities';
COMMENT ON COLUMN swot_analysis.threats IS 'JSONB array of threats';
COMMENT ON COLUMN swot_analysis.is_latest IS 'Flag to identify the most recent SWOT analysis';

-- ===================================================
-- 8. SUCCESS_PREDICTIONS TABLE (CORE MILESTONE 2)
-- ===================================================
CREATE TABLE IF NOT EXISTS success_predictions (
    prediction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    success_probability INTEGER CHECK (success_probability >= 0 AND success_probability <= 100),
    overall_risk_score INTEGER CHECK (overall_risk_score >= 0 AND overall_risk_score <= 100),
    confidence_score INTEGER CHECK (confidence_score >= 0 AND confidence_score <= 100),
    prediction_details JSONB,
    prediction_date TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    is_latest BOOLEAN DEFAULT true,
    CONSTRAINT fk_success_predictions_projects FOREIGN KEY (project_id) 
        REFERENCES projects(project_id) ON DELETE CASCADE ON UPDATE CASCADE
);

COMMENT ON TABLE success_predictions IS 'Stores predictive results from ML/predictive analysis (Milestone 2 Core)';
COMMENT ON COLUMN success_predictions.success_probability IS 'Success probability from 0-100';
COMMENT ON COLUMN success_predictions.overall_risk_score IS 'Overall risk score from 0-100';
COMMENT ON COLUMN success_predictions.confidence_score IS 'Confidence level in the prediction from 0-100';
COMMENT ON COLUMN success_predictions.is_latest IS 'Flag to identify the most recent prediction';

-- ===================================================
-- 9. RECOMMENDATIONS TABLE (CORE MILESTONE 2)
-- ===================================================
CREATE TABLE IF NOT EXISTS recommendations (
    recommendation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    recommendation_text TEXT NOT NULL,
    category VARCHAR(100),
    risk_mitigation TEXT,
    priority VARCHAR(20) CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    expected_impact TEXT,
    implementation_steps JSONB,
    generated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    is_latest BOOLEAN DEFAULT true,
    CONSTRAINT fk_recommendations_projects FOREIGN KEY (project_id) 
        REFERENCES projects(project_id) ON DELETE CASCADE ON UPDATE CASCADE
);

COMMENT ON TABLE recommendations IS 'Stores recommendations and risk mitigation suggestions (Milestone 2 Core)';
COMMENT ON COLUMN recommendations.implementation_steps IS 'JSONB array of implementation steps';

-- ===================================================
-- 10. ASSESSMENT_REPORTS TABLE
-- ===================================================
CREATE TABLE IF NOT EXISTS assessment_reports (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    report_path TEXT NOT NULL,
    report_type VARCHAR(50) DEFAULT 'PDF',
    report_summary TEXT,
    generated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    is_latest BOOLEAN DEFAULT true,
    CONSTRAINT fk_assessment_reports_projects FOREIGN KEY (project_id) 
        REFERENCES projects(project_id) ON DELETE CASCADE ON UPDATE CASCADE
);

COMMENT ON TABLE assessment_reports IS 'Stores references to generated project assessment reports';
COMMENT ON COLUMN assessment_reports.report_path IS 'Path, URL, or object-storage key to the report';

