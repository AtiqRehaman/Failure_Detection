-- Query 1: Get complete assessment for a project
SELECT 
    p.project_id,
    p.project_name,
    p.industry,
    p.business_model,
    p.budget,
    u.name as owner_name,
    u.email as owner_email,
    ra.risk_score,
    ra.risk_category,
    ra.priority_level as risk_priority,
    swot.strengths,
    swot.weaknesses,
    swot.opportunities,
    swot.threats,
    sp.success_probability,
    sp.overall_risk_score,
    sp.confidence_score,
    ar.report_path,
    ar.generated_at as report_generated_at
FROM Projects p
JOIN Users u ON p.user_id = u.user_id
LEFT JOIN Risk_Assessments ra ON p.project_id = ra.project_id
LEFT JOIN SWOT_Analysis swot ON p.project_id = swot.project_id
LEFT JOIN Success_Predictions sp ON p.project_id = sp.project_id
LEFT JOIN Assessment_Reports ar ON p.project_id = ar.project_id
WHERE p.project_id = 1
ORDER BY ra.assessment_date DESC, swot.generated_at DESC, sp.prediction_date DESC, ar.generated_at DESC
LIMIT 1;

-- Query 2: Get all risk assessments for a project with category breakdown
SELECT 
    risk_category,
    COUNT(*) as risk_count,
    AVG(risk_score) as avg_score,
    MAX(risk_score) as max_score,
    MIN(risk_score) as min_score,
    priority_level,
    string_agg(DISTINCT risk_description, '; ') as risk_descriptions
FROM Risk_Assessments
WHERE project_id = 1
GROUP BY risk_category, priority_level
ORDER BY avg_score DESC;

-- Query 3: Get project analytics summary
SELECT 
    COUNT(*) as total_projects,
    AVG(p.budget) as avg_budget,
    SUM(p.budget) as total_budget,
    AVG(sp.success_probability) as avg_success_rate,
    AVG(sp.overall_risk_score) as avg_risk_score,
    COUNT(DISTINCT p.industry) as unique_industries,
    COUNT(DISTINCT p.business_model) as unique_business_models,
    COUNT(DISTINCT p.user_id) as unique_users
FROM Projects p
LEFT JOIN Success_Predictions sp ON p.project_id = sp.project_id
WHERE p.status = 'completed';

-- Query 4: Get detailed SWOT analysis for a project with categories
SELECT 
    swot_id,
    jsonb_array_elements_text(strengths) as strength,
    jsonb_array_elements_text(weaknesses) as weakness,
    jsonb_array_elements_text(opportunities) as opportunity,
    jsonb_array_elements_text(threats) as threat,
    generated_at
FROM SWOT_Analysis
WHERE project_id = 1
ORDER BY generated_at DESC
LIMIT 1;

-- Query 5: Get recommendations by priority for a project
SELECT 
    recommendation_text,
    priority,
    category,
    target_area,
    is_applied,
    generated_at
FROM Recommendations
WHERE project_id = 1
ORDER BY 
    CASE priority 
        WHEN 'CRITICAL' THEN 1 
        WHEN 'HIGH' THEN 2 
        WHEN 'MEDIUM' THEN 3 
        WHEN 'LOW' THEN 4 
    END,
    generated_at DESC;

-- Query 6: Get user activity summary
SELECT 
    u.user_id,
    u.name,
    u.email,
    u.role,
    COUNT(DISTINCT p.project_id) as total_projects,
    COUNT(DISTINCT al.log_id) as total_activities,
    MAX(al.timestamp) as last_activity,
    COUNT(DISTINCT ar.report_id) as total_reports
FROM Users u
LEFT JOIN Projects p ON u.user_id = p.user_id
LEFT JOIN Analytics_Logs al ON u.user_id = al.user_id
LEFT JOIN Assessment_Reports ar ON p.project_id = ar.project_id
WHERE u.is_active = true
GROUP BY u.user_id, u.name, u.email, u.role
ORDER BY total_projects DESC;

