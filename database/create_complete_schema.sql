-- VIEW: vw_Project_Complete_Assessment
-- ============================================================
-- Purpose: Provides a comprehensive view of all assessment data for a project
-- ============================================================

CREATE OR REPLACE VIEW vw_Project_Complete_Assessment AS
SELECT 
    p.project_id,
    p.project_name,
    p.industry,
    p.business_model,
    p.budget,
    p.status,
    p.created_at as project_submitted_at,
    u.name as owner_name,
    u.email as owner_email,
    
    -- Latest Risk Assessment
    ra.risk_score as latest_overall_risk_score,
    ra.assessment_date as latest_risk_assessment_date,
    
    -- Latest SWOT Analysis
    swot.strengths,
    swot.weaknesses,
    swot.opportunities,
    swot.threats,
    swot.generated_at as swot_generated_at,
    
    -- Latest Success Prediction
    sp.success_probability,
    sp.confidence_score,
    sp.prediction_date,
    
    -- Assessment Report
    ar.report_path,
    ar.generated_at as report_generated_at,
    ar.download_count as report_download_count
    
FROM Projects p
JOIN Users u ON p.user_id = u.user_id
LEFT JOIN LATERAL (
    SELECT * FROM Risk_Assessments 
    WHERE project_id = p.project_id 
    ORDER BY assessment_date DESC LIMIT 1
) ra ON true
LEFT JOIN LATERAL (
    SELECT * FROM SWOT_Analysis 
    WHERE project_id = p.project_id 
    ORDER BY generated_at DESC LIMIT 1
) swot ON true
LEFT JOIN LATERAL (
    SELECT * FROM Success_Predictions 
    WHERE project_id = p.project_id 
    ORDER BY prediction_date DESC LIMIT 1
) sp ON true
LEFT JOIN LATERAL (
    SELECT * FROM Assessment_Reports 
    WHERE project_id = p.project_id 
    ORDER BY generated_at DESC LIMIT 1
) ar ON true;

COMMENT ON VIEW vw_Project_Complete_Assessment IS 'Provides a comprehensive view of all assessment data for a project';

